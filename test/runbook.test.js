function base(type, extra) {
  clock += 1000;
  return { type, timestamp: new Date(T0 + clock).toISOString(), cwd: CWD, gitBranch: 'fix/vpn', sessionId: 's-1', ...extra };
}
const prompt = (text, extra = {}) => base('user', { message: { role: 'user', content: text }, ...extra });
const say = (text) => base('assistant', { message: { role: 'assistant', content: [{ type: 'text', text }] } });
function call(name, input) {
  const id = 'toolu_' + (++ids);
  return { id, line: base('assistant', { message: { role: 'assistant', content: [{ type: 'tool_use', id, name, input }] } }) };
}
function result(id, content, isError, toolUseResult) {
  const block = { type: 'tool_result', tool_use_id: id, content };
  if (isError) block.is_error = true;
  return base('user', { message: { role: 'user', content: [block] }, ...(toolUseResult ? { toolUseResult } : {}) });
}
/** A tool call plus its result, as two lines. */
function tool(name, input, opts = {}) {
  const c = call(name, input);
  return [c.line, result(c.id, opts.out || 'ok', !!opts.error, opts.tur)];
}
const bash = (command, description, opts) => tool('Bash', description ? { command, description } : { command }, opts);
const ps = (command, description, opts) => tool('PowerShell', description ? { command, description } : { command }, opts);

function write(name, lines) {
  const f = path.join(dir, name);
  fs.writeFileSync(f, lines.flat().map((l) => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n');
  return f;
}

